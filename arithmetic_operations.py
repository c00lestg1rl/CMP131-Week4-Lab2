# Program Title 
print('****Program for Basic Arithmetic Operations***')

# User Input 
value1= float(input('Enter a number:'))
value2= float(input('Enter a second number that is not 0:'))

# Calculations
addition_result= value1 + value2

subtraction_result= value1 - value2

multiplication_result= value1 * value2

division_result= value1 / value2 

power_result= (value1) ** value2

average= ((addition_result) / 2)

# Output
print('Addition Operation Result:', addition_result)
print('Subtraction Operation Result:', subtraction_result)
